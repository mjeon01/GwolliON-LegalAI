import {createRequire} from "node:module";
import {mkdirSync,writeFileSync} from "node:fs";
import assert from "node:assert/strict";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||"playwright");
const base=process.env.GWOLLION_URL||"http://127.0.0.1:8020";
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1100}});
const page=await context.newPage(),ids=[],errors=[],report={checks:[]};
page.on("pageerror",e=>errors.push(e.message));
mkdirSync("var/mvp-review",{recursive:true});
try {
 await page.goto(base);await page.locator(".sample-card").last().waitFor();
 assert(await page.locator("#live-evidence").isChecked());
 const status=await (await context.request.get(`${base}/api/evidence/status`)).json();
 assert.equal(status.corpus.status,"ready");assert.equal(status.corpus.records,182424);
 assert(status.official_api_configured);
 await page.locator('[data-sample="lease-return"]').click();
 await page.waitForFunction(()=>document.querySelector("#document-text").value.includes("새 임차인"));
 if (!(await page.locator("#engine").isVisible())) await page.locator("#review-settings > summary").click();
 await page.locator("#engine").selectOption(process.argv.includes("--ai")?"ollama":"rules");
 await page.locator("#analyze-button").click();
 await page.locator("#result-view").waitFor({state:"visible",timeout:220000});
 const id=page.url().split("#analysis=")[1];ids.push(id);
 const result=await (await context.request.get(`${base}/api/analyses/${id}`)).json();
 assert.equal(result.evidence_mode,"live");assert.equal(result.review.verdict,"warning");
 assert(!result.grounding.failures.some(f=>f.target==="law"||f.target==="configuration"));
 assert(result.sources.some(s=>s.kind==="precedent"));
 assert(result.sources.some(s=>s.kind==="dataset"&&s.split==="Training"));
 assert(result.sources.filter(s=>s.kind==="law").every(s=>["live","cache"].includes(s.retrieval_method)));
 await page.locator("#grounding-panel > summary").click();
 assert(await page.locator('#grounding-panel [data-source-kind="precedent"]').count());
 assert(await page.locator('#grounding-panel [data-source-kind="dataset"]').count());
 await page.locator('#grounding-panel [data-source-kind="dataset"] > summary').first().click();
 assert((await page.locator("#grounding-sources").textContent()).includes("현재 법률"));
 await page.screenshot({path:"var/mvp-review/evidence-desktop.png",fullPage:true});
 await page.setViewportSize({width:375,height:900});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.locator("#grounding-panel").scrollIntoViewIfNeeded();
 await page.screenshot({path:"var/mvp-review/evidence-mobile.png",fullPage:false});
 await page.setViewportSize({width:1440,height:1100});
 report.checks.push("default live retrieval; verified law versions, official precedent and Training references; mobile source panel");
 // Change the event date: source versions must be retrieved again.
 const revised=await (await context.request.post(`${base}/api/analyses/${id}/answers`,{timeout:220000,data:{analysis_revision:1,context:{...result.context,event_date:"2020-01-01"}}})).json();
 assert.equal(revised.analysis_revision,2);
 assert.equal(revised.grounding.target_date,"2020-01-01");
 assert(revised.sources.filter(s=>s.kind==="law").every(s=>s.effective_date<="2020-01-01"));
 report.checks.push("event-date revision retrieves historical law and excludes later decisions");
 report.sources=result.sources.map(s=>({source_id:s.source_id,kind:s.kind,title:s.title,effective_date:s.effective_date,decision_date:s.decision_date}));
 report.historical_sources=revised.sources.filter(s=>s.kind==="law").map(s=>({title:s.title,effective_date:s.effective_date}));
 report.semantic=result.extraction.semantic_review;
 assert.deepEqual(errors,[]);
 writeFileSync("var/mvp-review/evidence-report.json",JSON.stringify(report,null,2));
 console.log(JSON.stringify({checks:report.checks,source_count:result.sources.length},null,2));
} finally {
 for(const id of ids)await context.request.delete(`${base}/api/analyses/${id}`);
 await context.request.dispose();
 await context.close();
 await browser.close();
}
